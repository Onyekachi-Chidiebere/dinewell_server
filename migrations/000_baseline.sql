-- Fresh PostgreSQL baseline. Table and column names intentionally mirror the
-- Sequelize model options (freezeTableName/tableName and timestamp mappings).

DO $$ BEGIN
  CREATE TYPE enum_payment_payment_status AS ENUM ('pending', 'completed', 'failed', 'reversal');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE enum_payment_type AS ENUM ('debit', 'reversal');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE enum_points_status AS ENUM ('pending', 'completed');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE enum_points_type AS ENUM ('issue', 'redeem');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS "user" (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stripe_id VARCHAR(255),
  restaurant_name VARCHAR(255),
  name VARCHAR(255),
  phone VARCHAR(255),
  email VARCHAR(255),
  account_name VARCHAR(255),
  bank_name VARCHAR(255),
  account_number VARCHAR(255),
  bank_code VARCHAR(255),
  type VARCHAR(255),
  password VARCHAR(255),
  approval_status INTEGER,
  date_created TIMESTAMPTZ,
  phone_verification_date TIMESTAMPTZ,
  email_verification_date TIMESTAMPTZ,
  date_approved TIMESTAMPTZ,
  regions JSONB DEFAULT '[]'::jsonb,
  payment_cards JSONB DEFAULT '[]'::jsonb,
  default_payment_card_id VARCHAR(255),
  cash_payment BOOLEAN DEFAULT TRUE,
  wallet_amount INTEGER DEFAULT 0,
  pending_wallet_amount INTEGER,
  points_blocked BOOLEAN NOT NULL DEFAULT FALSE,
  payment_failed BOOLEAN NOT NULL DEFAULT FALSE,
  restaurant_logo VARCHAR(255),
  restaurant_images JSONB DEFAULT '[]'::jsonb,
  username VARCHAR(255),
  date_of_birth TIMESTAMPTZ,
  gender VARCHAR(50),
  provider VARCHAR(50),
  provider_id VARCHAR(255),
  profile_image VARCHAR(500),
  app_notifications BOOLEAN NOT NULL DEFAULT TRUE,
  email_notifications BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS user_username_key ON "user"(username);
CREATE INDEX IF NOT EXISTS user_email_type_idx ON "user"(email, type);

CREATE TABLE IF NOT EXISTS platform_settings (
  id INTEGER PRIMARY KEY DEFAULT 1,
  customer_earn_rate DECIMAL(10,4) NOT NULL DEFAULT 10,
  customer_redeem_rate DECIMAL(10,4) NOT NULL DEFAULT 500,
  merchant_billing_rate DECIMAL(10,4) NOT NULL DEFAULT 0.1,
  debt_limit_usd DECIMAL(12,2) NOT NULL DEFAULT 100,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dishes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES "user"(id),
  dish_name VARCHAR(255) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  points_per_dollar DECIMAL(5,2) DEFAULT 0,
  dish_image_url VARCHAR(500),
  base_points_per_dish INTEGER DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  date_created TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  date_updated TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS dishes_restaurant_id_idx ON dishes(restaurant_id);

CREATE TABLE IF NOT EXISTS payment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES "user"(id),
  restaurant_name VARCHAR(255),
  amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  points_issued INTEGER NOT NULL DEFAULT 0,
  payment_status enum_payment_payment_status NOT NULL DEFAULT 'pending',
  payment_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  stripe_payment_intent_id VARCHAR(255),
  points_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
  type enum_payment_type NOT NULL DEFAULT 'debit',
  description VARCHAR(255),
  card_last4 VARCHAR(4),
  card_brand VARCHAR(50),
  error_message TEXT,
  idempotency_key VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS payment_restaurant_id_idx ON payment(restaurant_id);
CREATE INDEX IF NOT EXISTS payment_stripe_intent_idx ON payment(stripe_payment_intent_id);
CREATE UNIQUE INDEX IF NOT EXISTS payment_idempotency_key_idx
  ON payment(idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS points (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status enum_points_status NOT NULL DEFAULT 'pending',
  type enum_points_type NOT NULL,
  restaurant_id INTEGER NOT NULL REFERENCES "user"(id),
  customer_id INTEGER REFERENCES "user"(id),
  dishes JSONB NOT NULL DEFAULT '[]'::jsonb,
  total_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  total_points INTEGER NOT NULL DEFAULT 0,
  points_per_dollar DECIMAL(5,2) NOT NULL DEFAULT 10,
  qr_code VARCHAR(255),
  date_created TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  date_used TIMESTAMPTZ,
  notes TEXT,
  paid BOOLEAN NOT NULL DEFAULT FALSE,
  payment_id INTEGER REFERENCES payment(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS points_qr_code_key ON points(qr_code);
CREATE INDEX IF NOT EXISTS points_restaurant_id_idx ON points(restaurant_id);
CREATE INDEX IF NOT EXISTS points_customer_id_idx ON points(customer_id);
CREATE INDEX IF NOT EXISTS points_payment_id_idx ON points(payment_id);

CREATE TABLE IF NOT EXISTS notification (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES "user"(id),
  title VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  type VARCHAR(80) NOT NULL DEFAULT 'general',
  data JSONB DEFAULT '{}'::jsonb,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  date_created TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS notification_user_id_idx ON notification(user_id);

CREATE TABLE IF NOT EXISTS device_token (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES "user"(id),
  token VARCHAR(512) NOT NULL,
  platform VARCHAR(20) NOT NULL DEFAULT 'unknown',
  app VARCHAR(20),
  date_updated TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS device_token_token_key ON device_token(token);
CREATE INDEX IF NOT EXISTS device_token_user_id_idx ON device_token(user_id);

CREATE TABLE IF NOT EXISTS sockets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES "user"(id),
  socket_id VARCHAR(255) NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS sockets_user_id_idx ON sockets(user_id);

CREATE TABLE IF NOT EXISTS admin_bootstrap_token (
  token_hash VARCHAR(64) PRIMARY KEY,
  admin_user_id INTEGER NOT NULL REFERENCES "user"(id),
  consumed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
